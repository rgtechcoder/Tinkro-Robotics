const fs = require("fs");
const path = require("path");
const Prerenderer = require("@prerenderer/prerenderer");
const PuppeteerRenderer = require("@prerenderer/renderer-puppeteer");

const chromeExecutablePath =
  process.env.PUPPETEER_EXECUTABLE_PATH ||
  (fs.existsSync("C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe")
    ? "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe"
    : undefined);

process.env.PUPPETEER_SKIP_CHROMIUM_DOWNLOAD = "1";

const staticDir = path.join(__dirname, "..", "dist");

/*
 * ============================================================
 * TEST MODE
 * ============================================================
 *
 * IMPORTANT:
 * For this test we intentionally prerender ONLY ONE product.
 *
 * After confirming that the generated HTML contains:
 *
 *   "priceCurrency": "INR"
 *   "price": 42.12
 *
 * we will remove TEST_MODE and enable all 100+ product routes.
 *
 * ============================================================
 */

const TEST_MODE = true;

/*
 * ============================================================
 * ROUTES
 * ============================================================
 */

let routes = [
  "/",
  "/products",
  "/labs",
  "/blog",
  "/about",
  "/contact",
  "/faq",
  "/shipping-policy",
  "/returns",
  "/warranty",
  "/track-order",
];

/*
 * ============================================================
 * TEST MODE: ONLY ONE PRODUCT
 * ============================================================
 *
 * Do NOT load route-discovery.json during this test.
 *
 * This prevents all 135 product routes from being prerendered.
 */

if (TEST_MODE) {
  routes = ["/product/jumper-cable-male-male"];

  console.log("");
  console.log("==============================================");
  console.log(" PRERENDER TEST MODE");
  console.log("==============================================");
  console.log("");
  console.log("Only one product will be prerendered:");
  console.log("/product/jumper-cable-male-male");
  console.log("");
} else {
  /*
   * ============================================================
   * PRODUCTION MODE
   * ============================================================
   *
   * When TEST_MODE is false, load all routes generated by
   * generate-sitemap.mjs / route-discovery.json.
   */

  try {
    const discoveryPath = path.join(
      __dirname,
      "..",
      "public",
      "route-discovery.json",
    );

    if (fs.existsSync(discoveryPath)) {
      const raw = fs.readFileSync(discoveryPath, "utf8");
      const discovery = JSON.parse(raw);

      if (discovery && Array.isArray(discovery.routes)) {
        const additional = discovery.routes.filter(
          (route) => !routes.includes(route),
        );

        routes = [...routes, ...additional];

        console.log(
          `[prerender] Loaded ${additional.length} routes from route-discovery.json`,
        );
      }
    } else {
      console.log(
        "[prerender] route-discovery.json not found; proceeding with static routes only",
      );
    }
  } catch (err) {
    console.error(
      "[prerender] Failed to load route-discovery.json:",
      err,
    );
  }
}

/*
 * ============================================================
 * RUN PRERENDER
 * ============================================================
 */

async function run() {
  if (!fs.existsSync(staticDir)) {
    throw new Error(
      `Prerender failed: dist folder not found at ${staticDir}`,
    );
  }

  console.log("");
  console.log(`[prerender] Static directory: ${staticDir}`);
  console.log(`[prerender] Routes to render: ${routes.length}`);
  console.log("");

  const prerenderer = new Prerenderer({
    staticDir,

    renderer: new PuppeteerRenderer({
      /*
       * Give React/Firestore enough time to load the product.
       */
      renderAfterTime: 5000,

      /*
       * Only one route in test mode anyway.
       * Keep this conservative for now.
       */
      maxConcurrentRoutes: 1,

      executablePath: chromeExecutablePath,

      headless: true,

      timeout: 60000,

      navigationOptions: {
        waitUntil: "load",
        timeout: 60000,
      },

      /*
       * IMPORTANT:
       *
       * Firestore/Firebase requests are required to load
       * the product data during prerendering.
       *
       * Therefore this MUST be false for this test.
       */
      skipThirdPartyRequests: false,

      consoleHandler: (route, message) => {
        console.log(
          `[prerender:${route}] ${message.type()}: ${message.text()}`,
        );
      },
    }),
  });

  try {
    await prerenderer.initialize();

    let successCount = 0;

    for (const route of routes) {
      let rendered = false;

      console.log("");
      console.log("--------------------------------------------------");
      console.log(`[prerender] Rendering: ${route}`);
      console.log("--------------------------------------------------");

      for (let attempt = 1; attempt <= 2; attempt += 1) {
        try {
          console.log(
            `[prerender] Attempt ${attempt}/2: ${route}`,
          );

          const renderedRoutes =
            await prerenderer.renderRoutes([route]);

          renderedRoutes.forEach((renderedRoute) => {
            const normalizedRoute =
              renderedRoute.route.replace(/^\/+/, "");

            const outputPath =
              normalizedRoute === ""
                ? path.join(staticDir, "index.html")
                : path.join(
                    staticDir,
                    normalizedRoute,
                    "index.html",
                  );

            fs.mkdirSync(path.dirname(outputPath), {
              recursive: true,
            });

            fs.writeFileSync(
              outputPath,
              renderedRoute.html.trim(),
              "utf8",
            );

            console.log(
              `[prerender] Saved: ${outputPath}`,
            );
          });

          successCount += renderedRoutes.length;
          rendered = true;

          console.log(
            `[prerender] SUCCESS: ${route}`,
          );

          break;
        } catch (error) {
          console.error(
            `[prerender] Route failed (attempt ${attempt}): ${route}`,
          );

          console.error(error);
        }
      }

      if (!rendered) {
        console.error(
          `[prerender] Giving up on route: ${route}`,
        );
      }
    }

    console.log("");
    console.log("==============================================");
    console.log(" PRERENDER COMPLETE");
    console.log("==============================================");
    console.log("");
    console.log(
      `[prerender] Rendered ${successCount} routes successfully.`,
    );
    console.log("");
  } finally {
    prerenderer.destroy();
  }
}

run().catch((error) => {
  console.error("");
  console.error("==============================================");
  console.error(" PRERENDER FAILED");
  console.error("==============================================");
  console.error("");
  console.error(error);
  process.exit(1);
});